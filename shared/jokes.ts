function hash(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** 오늘(YYYY-MM-DD) 띠지에 돌릴 농담 n개. 같은 날엔 모두 같고, 한 바퀴 도는 동안엔 겹치지 않는다 */
export function jokesOfDay(today: string, n = 10, list: string[] = JOKES): string[] {
  if (!list.length) return [];
  const day = Math.floor(Date.parse(`${today}T00:00:00Z`) / 86_400_000);
  const perCycle = Math.max(1, Math.floor(list.length / n));
  const cycle = Math.floor(day / perCycle);
  const start = (((day % perCycle) + perCycle) % perCycle) * n;
  const order = list.map((_, i) => i);
  const r = rng(hash(`lunch-jokes:${cycle}`));
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1));
    [order[i], order[j]] = [order[j]!, order[i]!];
  }
  return order.slice(start, start + n).map((i) => list[i]!);
}
